const L = (l: string): number => ({ ก: 0, ข: 1, ค: 2, ง: 3 }[l] ?? 0);

function q(
  id: string,
  num: number,
  question: string,
  choices: [string, string, string, string],
  answer: number,
  topic: string
): Question {
  const category: Question['category'] =
    topic === 'จรรยาบรรณ' ? 'จรรยาบรรณและศีลธรรม' : 'ความรู้ประกันชีวิต';
  return {
    id,
    category,
    topic,
    subtopic: topic,
    difficulty: 'medium',
    type: 'scenario',
    question,
    choices,
    correctAnswer: answer,
    answer,
    explanation: '',
    reference: '',
    references: [],
    tags: [id.split('-')[0], `ข้อ ${num}`],
    weight: 1,
    estimatedTime: 90,
    sourceDocumentId: id.split('-')[0],
  };
}

